  `${lineId}:${stationCode}`;

export const getAllTransitStations = () =>
  BANGKOK_TRANSIT_LINES.flatMap((line) =>
    line.stations.map((station) => ({
      ...station,
      lineId: line.id,
      lineName: line.name,
      lineColor: line.color,
      key: getStationKey(line.id, station.code),
    }))
  );